#!/usr/bin/env python3
"""Generate the Swift port's mel-filter constant and feature fixtures.

Writes:
  ports/tyger-swift/Sources/TygerVoice/MelFilters.generated.swift  (slaney 128x257)
  ports/tyger-swift/Tests/TygerVoiceTests/fixtures.json            (audio -> features)

`swift test` asserts MelFeatures.process matches the Python extractor (the oracle).
Regenerate after any change on either side:
    TYGER_S2S=~/dev/tyger-s2s python3 scripts/tyger-swift-fixtures.py
"""
import json
import os
import sys
from pathlib import Path

import numpy as np

S2S = os.environ.get("TYGER_S2S", os.path.expanduser("~/dev/tyger-s2s"))
BUNDLE = os.environ.get("TYGER_BUNDLE", os.path.expanduser(
    "~/.cache/huggingface/hub/models--nineninesix--tyger/snapshots/a5d4d73bb74fa4a7082dcd4387e44a1e5ac151b6"))
sys.path.insert(0, S2S)
sys.path.insert(0, os.path.join(S2S, "scripts"))

ROOT = Path(__file__).resolve().parents[1]
FILT_SWIFT = ROOT / "ports/tyger-swift/Sources/TygerVoice/MelFilters.generated.swift"
FIXTURES = ROOT / "ports/tyger-swift/Tests/TygerVoiceTests/fixtures.json"


def main():
    from app.plugins.ears.tyger.bundle import load as bundle_load

    _asr, proc, _tt, _cfg = bundle_load(Path(BUNDLE))
    mf = proc.feature_extractor.mel_filters.numpy().astype(np.float32)  # (128, 257)
    assert mf.shape == (128, 257), mf.shape

    vals = ", ".join(f"{v:.9g}" for v in mf.reshape(-1))
    FILT_SWIFT.write_text(
        "// Generated by scripts/tyger-swift-fixtures.py — librosa slaney mel, do not edit.\n"
        "let kMelFilters: [Float] = [" + vals + "]\n")
    print(f"wrote {FILT_SWIFT.name} ({mf.size} taps)")

    rng = np.random.default_rng(0)
    cases = {
        "silence_02s": np.zeros(3200, np.float32),
        "impulse_02s": np.tile([1.0, 0, 0, 0], 800).astype(np.float32),
        "tone440_05s": (0.5 * np.sin(2 * np.pi * 440 * np.arange(8000) / 16000)).astype(np.float32),
        "noise_05s": rng.standard_normal(8000).astype(np.float32) * 0.1,
        "noise_2s_sampled": rng.standard_normal(32000).astype(np.float32) * 0.1,
    }
    out = {"cases": []}
    for name, wav in cases.items():
        b = proc(wav, sampling_rate=16000, return_tensors="pt")
        feats = b["input_features"][0].numpy()  # (T, 128), masked rows already zero
        sample = list(range(len(feats))) if len(feats) <= 60 else [0, 1, 2, 49, 99, 149, 199]
        out["cases"].append({
            "name": name,
            "audio": [round(float(x), 6) for x in wav],
            "valid": int(b["attention_mask"][0].sum()),
            "sample_idx": sample,
            "frames": [[round(float(v), 5) for v in feats[i]] for i in sample],
        })
        print(f"  {name}: {len(feats)} frames, sampling {len(sample)}")
    FIXTURES.parent.mkdir(parents=True, exist_ok=True)
    FIXTURES.write_text(json.dumps(out))
    print(f"wrote {FIXTURES} ({FIXTURES.stat().st_size / 1e6:.2f} MB)")

    if "--runtime" in sys.argv:
        gen_runtime_fixtures()


def gen_runtime_fixtures():
    """Per-frame 8-vectors from the torch oracle (prev_state held at 0: the numeric
    chain in isolation — rules threading is covered by the Rust fixtures)."""
    import importlib.machinery
    import soundfile as sf
    import torch
    from app.plugins.ears.tyger.constants import SR
    from validate.reference import ReferenceEars

    torch.set_num_threads(4)
    te = importlib.machinery.SourceFileLoader(
        "te", str(ROOT / "scripts/tyger-eval.py")).load_module()
    from datasets import load_dataset
    from transformers import AutoModel

    rows = iter(load_dataset(te.DATASET, split="val", streaming=True))
    row = next(rows)
    T = int(row["num_frames"])
    limit = min(T, 250)  # 20 s
    codes = {ch: np.array(row[f"codes_{ch}"], dtype=np.int16).reshape(T, 8)[:limit] for ch in ("ch0", "ch1")}
    mimi = AutoModel.from_pretrained("kyutai/mimi", dtype=torch.float32).eval()
    wavs = {ch: te.resample16k(te.decode_channel(mimi, codes[ch])) for ch in ("ch0", "ch1")}

    ears = ReferenceEars(BUNDLE, device="cpu")
    outdir = FIXTURES.parent / "runtime"
    outdir.mkdir(parents=True, exist_ok=True)
    for ch in ("ch0", "ch1"):
        sf.write(outdir / f"{ch}.wav", wavs[ch], SR, subtype="FLOAT")

    hop = 5120
    n_hops = min(len(wavs["ch0"]), len(wavs["ch1"])) // hop
    frames = []
    for h in range(n_hops):
        s = (h + 1) * hop
        wins = {ch: wavs[ch][max(0, s - 8 * SR):s] for ch in ("ch0", "ch1")}
        hu, ha = ears.encode_l15(wins["ch0"]), ears.encode_l15(wins["ch1"])
        from app.plugins.ears.tyger import rules
        act = rules.frame_energy(wins["ch0"])
        for i in range(-min(4, len(hu), len(ha), len(act)), 0):
            out = ears.head_step(hu[i], ha[i], float(act[i]), 0)
            frames.append([round(float(v), 5) for v in np.asarray(out)])
    (outdir / "expectations.json").write_text(json.dumps({"hop_samples": hop, "frames": frames}))
    print(f"wrote runtime fixtures: {n_hops} hops, {len(frames)} frames")


if __name__ == "__main__":
    main()
